#!/usr/bin/env bash
#
# Generate Claude Code harness sets from harness/config.json + harness/lang.json + harness/templates,
# then verify every generated set with the policy test suite.
#
# Output:
#   sample_harness/<variant>/   one set per variant: "base" (no language) + each key of lang.json
#     .claude/settings.json, .claude/hooks/guard.sh, .claude/skills/*, .claude/agents/*, CLAUDE.md, AGENTS.md
#   harness/build/root/         the set this repository itself uses (base + config.root extras)
#
# Usage:
#   harness/scripts/generate.sh                # generate + test
#   harness/scripts/generate.sh --check-root   # also fail if the repository root differs from harness/build/root
#
# Exit: non-zero when a baseline check or an UNDER (looser than policy) case fails, or the root drifted.
#       OVER (stops work more than policy) is reported as a warning only.

set -euo pipefail
shopt -u patsub_replacement 2>/dev/null || true  # keep "&" literal in ${var//pattern/replacement}

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
H="$REPO/harness"
TPL="$H/templates"
OUT="$REPO/sample_harness"
ROOT_OUT="$H/build/root"
RUNNER="$TPL/skills/review-claude-config/scripts/run-tests.sh"
CHECK_ROOT=0
[[ "${1:-}" == "--check-root" ]] && CHECK_ROOT=1

command -v jq >/dev/null || { echo "Error: jq is required." >&2; exit 1; }
jq empty "$H/config.json" "$H/lang.json"

cfg() { jq -r "$1" "$H/config.json"; }
GH_READ="$(cfg '.gh_read')"
CURL="$(cfg '.curl')"
ATTRIBUTION="$(cfg '.attribution')"
[[ "$GH_READ" == allow || "$GH_READ" == ask ]] || { echo "Error: config.gh_read must be allow|ask" >&2; exit 1; }
[[ "$CURL" == allow || "$CURL" == ask ]] || { echo "Error: config.curl must be allow|ask" >&2; exit 1; }
[[ "$ATTRIBUTION" == true || "$ATTRIBUTION" == false ]] || { echo "Error: config.attribution must be true|false" >&2; exit 1; }
mapfile -t SKILLS < <(cfg '.skills // [] | join("\n")' | grep -v '^$' || true)
mapfile -t AGENTS < <(cfg '.agents // [] | join("\n")' | grep -v '^$' || true)
mapfile -t ROOT_AGENTS < <(cfg '.root.agents // [] | join("\n")' | grep -v '^$' || true)
mapfile -t LANGS < <(jq -r 'keys | join("\n")' "$H/lang.json")

# Regex for a command prefix: escape ERE metacharacters, spaces -> [[:space:]]+
re_escape() { sed -E 's/[][\.*^$()+?{}|]/\\&/g; s/ +/[[:space:]]+/g' <<<"$1"; }

# Every install/add command of every language: blocked unless stripped as a lockfile install
mapfile -t ALL_CMDS < <(jq -r '[.[][] | .install[], .add[]] | unique | join("\n")' "$H/lang.json")
verbs=(); bare=()
for c in "${ALL_CMDS[@]}"; do
  if [[ "$c" == *" "* ]]; then verbs+=("$(re_escape "$c")"); else bare+=("$(re_escape "$c")"); fi
done
PKG_VERBS="$(IFS='|'; echo "${verbs[*]:-@none@}")"
PKG_BARE="$(IFS='|'; echo "${bare[*]:-@none@}")"

GH_WRITES='["Bash(gh pr create *)","Bash(gh pr merge *)","Bash(gh pr comment *)","Bash(gh pr review *)","Bash(gh pr close *)","Bash(gh pr reopen *)","Bash(gh pr edit *)","Bash(gh pr ready *)","Bash(gh issue create *)","Bash(gh issue comment *)","Bash(gh issue close *)","Bash(gh issue reopen *)","Bash(gh issue edit *)","Bash(gh release create *)","Bash(gh release edit *)","Bash(gh release upload *)","Bash(gh workflow run *)","Bash(gh workflow enable *)","Bash(gh workflow disable *)","Bash(gh run rerun *)","Bash(gh run cancel *)","Bash(gh repo create *)","Bash(gh repo fork *)","Bash(gh label create *)","Bash(gh label edit *)","Bash(gh gist *)","Bash(gh api *)"]'

gen_settings() {
  jq --arg gh "$GH_READ" --arg curl "$CURL" --argjson attr "$ATTRIBUTION" --argjson ghw "$GH_WRITES" '
    .permissions.ask += (if $gh == "ask" then ["Bash(gh *)"] else $ghw end)
    | .permissions.ask += (if $curl == "ask" then ["Bash(curl *)", "Bash(wget *)"] else [] end)
    | if $attr then . else {attribution: {commit: "", pr: ""}} + . end
  ' "$TPL/settings.base.json"
}

gen_guard() {
  local variant="$1" rules="" tpl line lf
  while IFS=$'\t' read -r cmd lockfiles; do
    [[ -n "$cmd" ]] || continue
    line="    lock_ok '$(re_escape "$cmd")'"
    for lf in $lockfiles; do line+=" $(printf '%q' "$lf")"; done
    rules+="${rules:+$'\n'}$line"
  done < <(jq -r --arg v "$variant" '(.[$v] // [])[] | . as $m | .install[] | [., ($m.lockfiles | join(" "))] | @tsv' "$H/lang.json")
  [[ -n "$rules" ]] || rules="    # (no language enabled: every package install is blocked)"
  tpl="$(cat "$TPL/guard.sh")"
  tpl="${tpl//"@@GENERATED_NOTICE@@"/"GENERATED by harness/scripts/generate.sh from harness/templates/guard.sh (variant: $variant). Do not edit; change the template and regenerate."}"
  tpl="${tpl//"    # @@LOCK_RULES@@"/$rules}"
  tpl="${tpl//"@@PKG_VERBS@@"/$PKG_VERBS}"
  tpl="${tpl//"@@PKG_BARE@@"/$PKG_BARE}"
  printf '%s\n' "$tpl"
}

gen_cases() {
  local variant="$1"
  cat "$H/tests/cases/baseline.tsv" "$H/tests/cases/common.tsv" \
      "$H/tests/cases/gh_read-$GH_READ.tsv" "$H/tests/cases/curl-$CURL.tsv"
  echo "# --- packages (generated from harness/lang.json, variant: $variant) ---"
  jq -r --arg v "$variant" '
    to_entries[] | .key as $lang | .value[] | (.lockfiles | join(",")) as $l |
    ( .install[] as $i |
        if $lang == $v then "ASK\tBash\t\($i)\t\($l)", "BLOCK\tBash\t\($i)\t"
        else "BLOCK\tBash\t\($i)\t\($l)" end ),
    ( .add[] as $a | "BLOCK\tBash\t\($a) example-pkg\t\($l)" ),
    ( .install[] | select(test(" ")) | "BLOCK\tBash\t\(.) example-pkg\t\($l)" )
  ' "$H/lang.json"
}

# build_set VARIANT DEST AGENT...
build_set() {
  local variant="$1" dest="$2"; shift 2
  local s a
  mkdir -p "$dest/.claude/hooks"
  gen_settings > "$dest/.claude/settings.json"
  gen_guard "$variant" > "$dest/.claude/hooks/guard.sh"
  chmod 755 "$dest/.claude/hooks/guard.sh"
  for s in "${SKILLS[@]}"; do
    [[ -d "$TPL/skills/$s" ]] || { echo "Error: unknown skill '$s'" >&2; exit 1; }
    mkdir -p "$dest/.claude/skills"
    cp -R "$TPL/skills/$s" "$dest/.claude/skills/"
  done
  [[ -d "$dest/.claude/skills/review-claude-config" ]] && gen_cases "$variant" > "$dest/.claude/skills/review-claude-config/policy-cases.tsv"
  for a in "$@"; do
    [[ -f "$TPL/agents/$a.md" ]] || { echo "Error: unknown agent '$a'" >&2; exit 1; }
    mkdir -p "$dest/.claude/agents"
    cp "$TPL/agents/$a.md" "$dest/.claude/agents/"
  done
  cp "$TPL/CLAUDE.md" "$TPL/AGENTS.md" "$dest/"
}

# Clean previous output (generated, git-ignored directories only)
rm -rf "$OUT" "$H/build"

fail=0
cases_tmp="$(mktemp)"
trap 'rm -f "$cases_tmp"' EXIT

for v in base "${LANGS[@]}"; do
  echo "=== variant: $v"
  build_set "$v" "$OUT/$v" "${AGENTS[@]}"
  gen_cases "$v" > "$cases_tmp"
  bash "$RUNNER" --root "$OUT/$v" --cases "$cases_tmp" --quiet || fail=1
done

echo "=== root (base + config.root extras)"
build_set base "$ROOT_OUT" "${AGENTS[@]}" "${ROOT_AGENTS[@]}"

if [[ $CHECK_ROOT -eq 1 ]]; then
  drift=0
  diff -r --exclude=settings.local.json "$ROOT_OUT/.claude" "$REPO/.claude" || drift=1
  for f in CLAUDE.md AGENTS.md; do diff "$ROOT_OUT/$f" "$REPO/$f" || drift=1; done
  if [[ $drift -eq 1 ]]; then
    echo "Error: repository root differs from harness/build/root. Regenerate and copy it to the root (see README)." >&2
    [[ -n "${GITHUB_ACTIONS:-}" ]] && echo "::error::repository root .claude/CLAUDE.md/AGENTS.md drifted from the generated harness"
    fail=1
  else
    echo "root matches harness/build/root"
  fi
fi

exit $fail
